#!/usr/bin/env python3
"""Generate main/font8x16.c — the LCD board's 8x16 bitmap font.

Why generated rather than hand-built: main/display.c's 3x5 table is hand-built
for a good reason (at 3x5 a single pixel decides whether a 6 is readable), but
that reason does not survive at 8x16 — there, hand-building 95 glyphs is error
prone and a rasterizer does it better. The generator is checked in so the table
is reproducible rather than a magic blob someone has to trust.

Source is DejaVu Sans Mono, whose licence (a Bitstream Vera derivative) permits
redistribution of derived works; only the reserved font *names* are restricted,
and nothing here claims to be DejaVu. Rendered glyph bitmaps, not font software.

Run:  python3 tools/gen_font.py > main/font8x16.c
"""

import sys

from PIL import Image, ImageDraw, ImageFont

TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
PT = 14  # largest size whose every glyph fits an 8x16 cell (see fit check below)
Y_OFFSET = -1
THRESHOLD = 110
CELL_W, CELL_H = 8, 16
FIRST, LAST = 32, 126  # space..'~', including real lowercase


def glyph_columns(font, ch):
    """Render one character and return CELL_W column bitmaps, bit0 = top row."""
    # Rendered into a wider scratch cell first so a glyph wider than the cell is
    # detected rather than silently clipped, and so each glyph can be centred on
    # its own ink rather than on the font's advance width.
    pad = 8
    img = Image.new("L", (CELL_W + 2 * pad, CELL_H), 0)
    ImageDraw.Draw(img).text((pad, Y_OFFSET), ch, fill=255, font=font)
    px = img.load()

    on = [
        (x, y)
        for y in range(CELL_H)
        for x in range(CELL_W + 2 * pad)
        if px[x, y] > THRESHOLD
    ]
    if not on:
        return [0] * CELL_W  # space and friends

    xs = [x for x, _ in on]
    ink_w = max(xs) - min(xs) + 1
    if ink_w > CELL_W:
        raise SystemExit(f"glyph {ch!r} needs {ink_w}px, cell is {CELL_W}px")
    shift = min(xs) - (CELL_W - ink_w) // 2

    cols = []
    for cx in range(CELL_W):
        bits = 0
        for y in range(CELL_H):
            if px[cx + shift, y] > THRESHOLD:
                bits |= 1 << y
        cols.append(bits)
    return cols


def main():
    font = ImageFont.truetype(TTF, PT)
    out = sys.stdout.write
    out(f"""\
// Generated by tools/gen_font.py — do not edit by hand.
//
// {CELL_W}x{CELL_H} glyphs for the ST7789 board, ASCII {FIRST}..{LAST}.
//
// Not the 3x5 table scaled up. This panel's pixels are physically SMALLER than
// the 0.42" OLED's (0.103 vs 0.130 mm), so porting the small font unscaled
// renders text smaller than the screen it replaces; and scaling it 4x gives a
// 0.41mm stroke on a 1.23mm glyph, which is legible and looks like a
// calculator. At {CELL_W}x{CELL_H} the stroke-to-width ratio is ~1:8, i.e. normal text.
//
// Real lowercase, unlike the 3x5 table: that folds case purely to halve a
// hand-built table, and a generated one has no such reason. (ui.c still folds
// the debug row deliberately — see R-006.)
#include "canvas.h"

// clang-format off
// One row per glyph, which is the whole point of the layout — reflowing it to
// fill columns would make the table unreadable and would be undone by the next
// regeneration anyway.
static const uint16_t k_font8x16_cols[] = {{
""")
    for code in range(FIRST, LAST + 1):
        cols = glyph_columns(font, chr(code))
        # A raw backslash here would continue the // comment onto the next
        # line, which gcc rejects under -Werror=comment. Name the awkward ones.
        named = {32: "space", 92: "backslash"}
        pretty = named.get(code, chr(code))
        body = ", ".join(f"0x{c:04X}" for c in cols)
        out(f"    {body},  // {code} {pretty}\n")
    out(f"""}};
// clang-format on

const struct canvas_font canvas_font8x16 = {{
    .cols = k_font8x16_cols,
    .glyph_w = {CELL_W},
    .glyph_h = {CELL_H},
    .advance = {CELL_W},
    .line_h = {CELL_H},
    .first = {FIRST},
    .last = {LAST},
    .fold_lowercase = false,
}};
""")


if __name__ == "__main__":
    main()
