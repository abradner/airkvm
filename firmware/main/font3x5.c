// The 0.42" OLED's hand-built 3x5 font, moved out of display.c unchanged.
//
// Extracted mechanically (tools-assisted, not retyped) and widened from
// uint8_t to uint16_t columns so one renderer in canvas.h serves both this and
// the 8x16 table. The bit patterns are byte-for-byte the ones that were
// confirmed legible on the physical panel on 2026-08-31; test_canvas.c pins
// that with a golden render so the move is provable rather than asserted.
//
// 3x5 glyphs, one entry per column, bit 0 = top row. Covers space through '_'
// (ASCII 32..95); lowercase is folded to uppercase at draw time, which costs
// nothing here and halves the table.
//
// Deliberately hand-built rather than generated: at this size the difference
// between a readable 6 and an unreadable one is a single pixel, and the digits
// are what this screen exists to show.
#include "canvas.h"

